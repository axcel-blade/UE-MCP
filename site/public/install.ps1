# UnrealEngineMCP remote installer for Windows
# Usage:
#   irm https://axcel-blade.github.io/UE-MCP/install.ps1 | iex
# Save this file as UTF-8 without BOM. A BOM breaks irm|iex on Windows PowerShell 5.1.

$ErrorActionPreference = "Stop"

$RepoUrl = "https://github.com/axcel-blade/UE-MCP.git"
$Branch = if ($env:UE_MCP_BRANCH) { $env:UE_MCP_BRANCH } else { "main" }
$InstallDir = if ($env:UE_MCP_HOME) {
    $env:UE_MCP_HOME
} else {
    Join-Path $env:USERPROFILE "UE-MCP"
}

Write-Host "UnrealEngineMCP installer for Windows" -ForegroundColor Cyan
Write-Host "Install dir: $InstallDir"
Write-Host "Branch:      $Branch"

function Ensure-Uv {
    if (Get-Command uv -ErrorAction SilentlyContinue) { return }
    Write-Host "Installing uv..."
    try {
        winget install --id=astral-sh.uv -e --accept-package-agreements --accept-source-agreements
    } catch {
        Write-Host "winget install failed; trying uv bootstrap script..."
        irm https://astral.sh/uv/install.ps1 | iex
    }
    $env:Path = [System.Environment]::GetEnvironmentVariable("Path", "Machine") + ";" +
                [System.Environment]::GetEnvironmentVariable("Path", "User") + ";" +
                (Join-Path $env:USERPROFILE ".local\bin")
    if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {
        throw "uv not found after install. Open a new terminal and re-run."
    }
}

function Ensure-Repo {
    if (Test-Path (Join-Path $InstallDir ".git")) {
        Write-Host "Updating existing clone..."
        Set-Location $InstallDir
        # uv.lock is regenerated by `uv sync`; discard local edits so checkout/pull can proceed.
        git checkout -- uv.lock 2>$null
        # Explicit refspec so single-branch clones (e.g. old develop installs) can switch branches.
        git fetch origin "+refs/heads/${Branch}:refs/remotes/origin/${Branch}"
        git checkout -B $Branch "origin/$Branch"
        return
    }
    if (Test-Path $InstallDir) {
        throw "Directory exists but is not a git repo: $InstallDir. Set UE_MCP_HOME or remove it."
    }
    Write-Host "Cloning $RepoUrl ($Branch)..."
    git clone --branch $Branch --single-branch $RepoUrl $InstallDir
    Set-Location $InstallDir
}

function Save-JsonNoBom([string]$Path, $Object) {
    $text = $Object | ConvertTo-Json -Depth 20
    $utf8NoBom = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($Path, $text + [Environment]::NewLine, $utf8NoBom)
}

function Add-McpServer([string]$ConfigPath, [string]$RepoRoot) {
    if (-not (Test-Path $ConfigPath)) { return $false }
    $backup = "$ConfigPath.ue-mcp.bak"
    Copy-Item $ConfigPath $backup -Force
    $json = Get-Content $ConfigPath -Raw | ConvertFrom-Json
    if (-not $json.mcpServers) {
        $json | Add-Member -NotePropertyName mcpServers -NotePropertyValue (@{}) -Force
    }
    $entry = [pscustomobject]@{
        command = "uv"
        args    = @("run", "--directory", "$RepoRoot", "unreal-engine-mcp")
        env     = [pscustomobject]@{
            UNREAL_ENGINE_MCP_HOST = "127.0.0.1"
            UNREAL_ENGINE_MCP_PORT = "55557"
            UNREAL_ENGINE_MCP_SECURITY_MODE = "safe"
        }
    }
    $json.mcpServers | Add-Member -NotePropertyName unreal-engine-mcp -NotePropertyValue $entry -Force
    Save-JsonNoBom $ConfigPath $json
    Write-Host "Updated $ConfigPath (backup: $backup)"
    return $true
}

if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    throw "git is required. Install Git for Windows, then re-run."
}

Ensure-Uv
Ensure-Repo

Write-Host "Syncing project with uv..."
uv sync

$cursor = Join-Path $env:USERPROFILE ".cursor\mcp.json"
$claude = Join-Path $env:APPDATA "Claude\claude_desktop_config.json"
[void](Add-McpServer $cursor $InstallDir)
[void](Add-McpServer $claude $InstallDir)

Write-Host ""
Write-Host "Next steps:" -ForegroundColor Green
Write-Host "1. Install the plugin into your Unreal project:"
Write-Host '   uv run python scripts/install_plugin.py --project "D:\Path\To\YourProject.uproject"'
Write-Host "2. Open the project, enable UnrealEngineMCP and Editor Scripting Utilities, then compile/restart"
Write-Host "3. Confirm Output Log: bridge listening on 127.0.0.1:55557"
Write-Host "4. Fully quit and reopen your MCP client (Cursor / Claude Desktop)"
Write-Host "Done. Repo: $InstallDir"
